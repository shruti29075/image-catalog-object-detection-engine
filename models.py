"""
models.py
---------
Domain models for the Image Catalog, Object Detection, Metadata Management,
and Composite Image Generation System.

Core Design Principles:
1. Strict schema validation for bounding boxes and normalized coordinates.
2. Clear distinction between automatically generated fields and user-editable fields.
3. Provenance tracking (DetectionOrigin, edit history, timestamps).
4. Lock mechanism: Manual corrections are immutable sources of truth and cannot
   be silently overwritten by automated re-detection unless explicitly forced.
"""

from __future__ import annotations
from dataclasses import dataclass, field, asdict
from enum import Enum
from typing import List, Dict, Optional, Any, Tuple
import uuid
import datetime
import json


class DetectionOrigin(str, Enum):
    AUTO_DETECTED = "auto_detected"
    USER_MANUAL = "user_manual"
    USER_EDITED = "user_edited"


class DetectionStatus(str, Enum):
    PENDING = "pending"
    DETECTED = "detected"
    MANUALLY_VERIFIED = "manually_verified"
    MANUALLY_EDITED = "manually_edited"
    FAILED_NO_OBJECTS = "failed_no_objects"


class ImageCategory(str, Enum):
    PHOTOGRAPHIC = "photographic"
    CARTOON = "cartoon"
    SYNTHETIC_SHAPES = "synthetic_shapes"
    COLOR_SWATCHES = "color_swatches"
    COMPOSITE = "composite"
    EMPTY = "empty"
    UNKNOWN = "unknown"


@dataclass
class BoundingBox:
    """
    Axis-aligned bounding box representation [x, y, width, height] in pixel coordinates.
    Origin (0,0) is at the top-left of the image.
    """
    x: int
    y: int
    width: int
    height: int

    def __post_init__(self):
        self.x = int(round(self.x))
        self.y = int(round(self.y))
        self.width = max(1, int(round(self.width)))
        self.height = max(1, int(round(self.height)))

    @property
    def x1(self) -> int:
        return self.x

    @property
    def y1(self) -> int:
        return self.y

    @property
    def x2(self) -> int:
        return self.x + self.width

    @property
    def y2(self) -> int:
        return self.y + self.height

    @property
    def area(self) -> int:
        return self.width * self.height

    @property
    def center(self) -> Tuple[int, int]:
        return (self.x + self.width // 2, self.y + self.height // 2)

    def to_dict(self) -> Dict[str, int]:
        return {
            "x": self.x,
            "y": self.y,
            "width": self.width,
            "height": self.height,
            "x2": self.x2,
            "y2": self.y2
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> BoundingBox:
        return cls(
            x=int(data["x"]),
            y=int(data["y"]),
            width=int(data["width"]),
            height=int(data["height"])
        )

    def iou(self, other: BoundingBox) -> float:
        """Calculate Intersection over Union (IoU) with another bounding box."""
        ix1 = max(self.x1, other.x1)
        iy1 = max(self.y1, other.y1)
        ix2 = min(self.x2, other.x2)
        iy2 = min(self.y2, other.y2)

        iw = max(0, ix2 - ix1)
        ih = max(0, iy2 - iy1)
        intersection = iw * ih

        if intersection == 0:
            return 0.0

        union = self.area + other.area - intersection
        return intersection / union if union > 0 else 0.0


@dataclass
class ColorInfo:
    """Color profile for an object or region."""
    primary_name: str
    primary_hex: str
    primary_rgb: Tuple[int, int, int]
    secondary_colors: List[str] = field(default_factory=list)
    clothing_colors: Optional[Dict[str, str]] = None  # e.g., {"shirt": "blue", "pants": "brown"}

    def to_dict(self) -> Dict[str, Any]:
        return {
            "primary_name": self.primary_name,
            "primary_hex": self.primary_hex,
            "primary_rgb": list(self.primary_rgb),
            "secondary_colors": self.secondary_colors,
            "clothing_colors": self.clothing_colors or {}
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> ColorInfo:
        rgb = tuple(data.get("primary_rgb", [0, 0, 0]))
        return cls(
            primary_name=data.get("primary_name", "unknown"),
            primary_hex=data.get("primary_hex", "#000000"),
            primary_rgb=(rgb[0], rgb[1], rgb[2]),
            secondary_colors=data.get("secondary_colors", []),
            clothing_colors=data.get("clothing_colors")
        )


@dataclass
class AutoGeneratedMetadata:
    """
    Immutable capture of fields produced by automatic detection.
    This guarantees that auto-detection results are preserved even when users
    override or edit fields.
    """
    detector_name: str
    model_version: str
    raw_label: str
    raw_confidence: float
    raw_bbox: BoundingBox
    detected_at: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "detector_name": self.detector_name,
            "model_version": self.model_version,
            "raw_label": self.raw_label,
            "raw_confidence": self.raw_confidence,
            "raw_bbox": self.raw_bbox.to_dict(),
            "detected_at": self.detected_at
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> AutoGeneratedMetadata:
        return cls(
            detector_name=data.get("detector_name", "standard"),
            model_version=data.get("model_version", "1.0"),
            raw_label=data.get("raw_label", ""),
            raw_confidence=float(data.get("raw_confidence", 0.0)),
            raw_bbox=BoundingBox.from_dict(data["raw_bbox"]),
            detected_at=data.get("detected_at", "")
        )


@dataclass
class UserEditableMetadata:
    """
    Tracks user manual modifications and corrections.
    """
    is_modified: bool = False
    modified_by: Optional[str] = None
    modified_at: Optional[str] = None
    notes: Optional[str] = None
    original_values_backup: Optional[Dict[str, Any]] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "is_modified": self.is_modified,
            "modified_by": self.modified_by,
            "modified_at": self.modified_at,
            "notes": self.notes,
            "original_values_backup": self.original_values_backup
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> UserEditableMetadata:
        return cls(
            is_modified=data.get("is_modified", False),
            modified_by=data.get("modified_by"),
            modified_at=data.get("modified_at"),
            notes=data.get("notes"),
            original_values_backup=data.get("original_values_backup")
        )


@dataclass
class DetectedObject:
    """
    Represents an individual detected (or manually added/edited) object within an image.
    Strictly differentiates between system-inferred values and user overrides.
    """
    id: str
    label: str                               # e.g., 'apple', 'boy', 'circle'
    display_name: str                        # User-friendly display title
    bbox: BoundingBox                        # Active bounding box
    confidence: float                        # Active confidence score (0.0 to 1.0)
    color: ColorInfo                         # Color attributes
    origin: DetectionOrigin                  # auto_detected vs user_manual vs user_edited
    auto_metadata: Optional[AutoGeneratedMetadata] = None  # Original auto detection snapshot
    user_metadata: UserEditableMetadata = field(default_factory=UserEditableMetadata)
    cutout_mask_path: Optional[str] = None   # Path to saved transparent alpha cutout (PNG)

    @classmethod
    def create_auto(
        cls,
        label: str,
        bbox: BoundingBox,
        confidence: float,
        color: ColorInfo,
        detector_name: str = "hybrid_visual_detector",
        model_version: str = "v2.4",
        cutout_mask_path: Optional[str] = None
    ) -> DetectedObject:
        """Factory method for system-generated detections."""
        now_iso = datetime.datetime.now(datetime.timezone.utc).isoformat()
        auto_meta = AutoGeneratedMetadata(
            detector_name=detector_name,
            model_version=model_version,
            raw_label=label,
            raw_confidence=confidence,
            raw_bbox=BoundingBox(bbox.x, bbox.y, bbox.width, bbox.height),
            detected_at=now_iso
        )
        return cls(
            id=str(uuid.uuid4())[:8],
            label=label,
            display_name=label.replace("_", " ").title(),
            bbox=bbox,
            confidence=confidence,
            color=color,
            origin=DetectionOrigin.AUTO_DETECTED,
            auto_metadata=auto_meta,
            user_metadata=UserEditableMetadata(is_modified=False),
            cutout_mask_path=cutout_mask_path
        )

    @classmethod
    def create_manual(
        cls,
        label: str,
        bbox: BoundingBox,
        color: ColorInfo,
        display_name: Optional[str] = None,
        confidence: float = 1.0,
        user_name: str = "user",
        notes: str = "Manually annotated object",
        cutout_mask_path: Optional[str] = None
    ) -> DetectedObject:
        """Factory method for user-added objects (e.g. when detection missed an object)."""
        now_iso = datetime.datetime.now(datetime.timezone.utc).isoformat()
        return cls(
            id=str(uuid.uuid4())[:8],
            label=label,
            display_name=display_name or label.replace("_", " ").title(),
            bbox=bbox,
            confidence=confidence,
            color=color,
            origin=DetectionOrigin.USER_MANUAL,
            auto_metadata=None,
            user_metadata=UserEditableMetadata(
                is_modified=True,
                modified_by=user_name,
                modified_at=now_iso,
                notes=notes
            ),
            cutout_mask_path=cutout_mask_path
        )

    def apply_user_edit(
        self,
        new_label: Optional[str] = None,
        new_bbox: Optional[BoundingBox] = None,
        new_confidence: Optional[float] = None,
        new_color: Optional[ColorInfo] = None,
        new_display_name: Optional[str] = None,
        user_name: str = "user",
        notes: Optional[str] = None
    ):
        """
        Applies a user correction to this object while preserving the auto_metadata snapshot.
        Transitions origin to USER_EDITED.
        """
        now_iso = datetime.datetime.now(datetime.timezone.utc).isoformat()
        # Backup pre-edit values on first edit
        if not self.user_metadata.original_values_backup:
            self.user_metadata.original_values_backup = {
                "label": self.label,
                "bbox": self.bbox.to_dict(),
                "confidence": self.confidence,
                "color": self.color.to_dict(),
                "display_name": self.display_name
            }

        if new_label is not None:
            self.label = new_label
        if new_display_name is not None:
            self.display_name = new_display_name
        if new_bbox is not None:
            self.bbox = new_bbox
        if new_confidence is not None:
            self.confidence = float(new_confidence)
        if new_color is not None:
            self.color = new_color

        self.origin = DetectionOrigin.USER_EDITED
        self.user_metadata.is_modified = True
        self.user_metadata.modified_by = user_name
        self.user_metadata.modified_at = now_iso
        if notes:
            self.user_metadata.notes = notes

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "label": self.label,
            "display_name": self.display_name,
            "bbox": self.bbox.to_dict(),
            "confidence": round(self.confidence, 4),
            "color": self.color.to_dict(),
            "origin": self.origin.value,
            "auto_metadata": self.auto_metadata.to_dict() if self.auto_metadata else None,
            "user_metadata": self.user_metadata.to_dict(),
            "cutout_mask_path": self.cutout_mask_path
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> DetectedObject:
        auto_meta = AutoGeneratedMetadata.from_dict(data["auto_metadata"]) if data.get("auto_metadata") else None
        user_meta = UserEditableMetadata.from_dict(data["user_metadata"]) if data.get("user_metadata") else UserEditableMetadata()
        return cls(
            id=data["id"],
            label=data["label"],
            display_name=data.get("display_name", data["label"]),
            bbox=BoundingBox.from_dict(data["bbox"]),
            confidence=float(data.get("confidence", 1.0)),
            color=ColorInfo.from_dict(data["color"]),
            origin=DetectionOrigin(data.get("origin", DetectionOrigin.AUTO_DETECTED.value)),
            auto_metadata=auto_meta,
            user_metadata=user_meta,
            cutout_mask_path=data.get("cutout_mask_path")
        )


@dataclass
class CompositeAssetSource:
    """Provenance entry linking a composite element back to its catalog image and detected object."""
    catalog_entry_id: str
    catalog_image_name: str
    object_id: str
    object_label: str
    applied_scale: float
    placement_bbox: BoundingBox
    z_index: int

    def to_dict(self) -> Dict[str, Any]:
        return {
            "catalog_entry_id": self.catalog_entry_id,
            "catalog_image_name": self.catalog_image_name,
            "object_id": self.object_id,
            "object_label": self.object_label,
            "applied_scale": round(self.applied_scale, 3),
            "placement_bbox": self.placement_bbox.to_dict(),
            "z_index": self.z_index
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> CompositeAssetSource:
        return cls(
            catalog_entry_id=data["catalog_entry_id"],
            catalog_image_name=data["catalog_image_name"],
            object_id=data["object_id"],
            object_label=data["object_label"],
            applied_scale=float(data["applied_scale"]),
            placement_bbox=BoundingBox.from_dict(data["placement_bbox"]),
            z_index=int(data.get("z_index", 0))
        )


@dataclass
class CompositeMetadata:
    """Metadata specific to composite images generated from catalog assets."""
    prompt: str
    source_assets: List[CompositeAssetSource]
    canvas_dimensions: Tuple[int, int]
    composition_strategy: str
    generated_at: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "prompt": self.prompt,
            "source_assets": [a.to_dict() for a in self.source_assets],
            "canvas_dimensions": list(self.canvas_dimensions),
            "composition_strategy": self.composition_strategy,
            "generated_at": self.generated_at
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> CompositeMetadata:
        dims = data.get("canvas_dimensions", [800, 600])
        return cls(
            prompt=data["prompt"],
            source_assets=[CompositeAssetSource.from_dict(a) for a in data.get("source_assets", [])],
            canvas_dimensions=(dims[0], dims[1]),
            composition_strategy=data.get("composition_strategy", "standard"),
            generated_at=data.get("generated_at", "")
        )


@dataclass
class CatalogEntry:
    """
    Primary unit of storage in the Image Catalog.
    Contains the asset file path, dimensions, category, list of detected/manual objects,
    status, and manual-correction locks.
    """
    id: str
    name: str                                # Unique friendly identifier (e.g., 'apple', 'boy')
    image_path: str                          # Path to original image file
    width: int
    height: int
    category: ImageCategory
    status: DetectionStatus
    objects: List[DetectedObject] = field(default_factory=list)
    has_manual_corrections: bool = False     # Lock flag: protects manual corrections from automatic overwrites
    is_composite: bool = False
    composite_metadata: Optional[CompositeMetadata] = None
    created_at: str = field(default_factory=lambda: datetime.datetime.now(datetime.timezone.utc).isoformat())
    updated_at: str = field(default_factory=lambda: datetime.datetime.now(datetime.timezone.utc).isoformat())

    def update_timestamp(self):
        self.updated_at = datetime.datetime.now(datetime.timezone.utc).isoformat()

    def add_object(self, obj: DetectedObject):
        self.objects.append(obj)
        if obj.origin in (DetectionOrigin.USER_MANUAL, DetectionOrigin.USER_EDITED):
            self.has_manual_corrections = True
            self.status = DetectionStatus.MANUALLY_EDITED
        self.update_timestamp()

    def remove_object(self, object_id: str) -> bool:
        initial_len = len(self.objects)
        self.objects = [o for o in self.objects if o.id != object_id]
        if len(self.objects) < initial_len:
            self.has_manual_corrections = True
            self.status = DetectionStatus.MANUALLY_EDITED
            self.update_timestamp()
            return True
        return False

    def get_object(self, object_id: str) -> Optional[DetectedObject]:
        for o in self.objects:
            if o.id == object_id:
                return o
        return None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "name": self.name,
            "image_path": self.image_path,
            "width": self.width,
            "height": self.height,
            "category": self.category.value,
            "status": self.status.value,
            "has_manual_corrections": self.has_manual_corrections,
            "is_composite": self.is_composite,
            "composite_metadata": self.composite_metadata.to_dict() if self.composite_metadata else None,
            "created_at": self.created_at,
            "updated_at": self.updated_at,
            "objects_count": len(self.objects),
            "objects": [o.to_dict() for o in self.objects]
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> CatalogEntry:
        objects = [DetectedObject.from_dict(o) for o in data.get("objects", [])]
        comp_meta = CompositeMetadata.from_dict(data["composite_metadata"]) if data.get("composite_metadata") else None
        return cls(
            id=data["id"],
            name=data["name"],
            image_path=data["image_path"],
            width=int(data["width"]),
            height=int(data["height"]),
            category=ImageCategory(data.get("category", ImageCategory.UNKNOWN.value)),
            status=DetectionStatus(data.get("status", DetectionStatus.PENDING.value)),
            objects=objects,
            has_manual_corrections=bool(data.get("has_manual_corrections", False)),
            is_composite=bool(data.get("is_composite", False)),
            composite_metadata=comp_meta,
            created_at=data.get("created_at", ""),
            updated_at=data.get("updated_at", "")
        )
